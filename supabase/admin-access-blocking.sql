ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS is_blocked boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS blocked_reason text,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

UPDATE public.profiles
SET is_blocked = false
WHERE is_blocked IS NULL;

UPDATE public.profiles
SET updated_at = now()
WHERE updated_at IS NULL;

-- Asegurar superadmin protegido (no puede ser bloqueado desde el panel)
UPDATE public.profiles
SET role = 'admin',
    is_blocked = false,
    blocked_reason = NULL,
    updated_at = now()
WHERE id = (
  SELECT id
  FROM auth.users
  WHERE LOWER(email) = 'kentoterakawa@gmail.com'
  LIMIT 1
);

CREATE TABLE IF NOT EXISTS public.admin_access_logs (
  id bigint generated by default as identity primary key,
  user_id uuid,
  email text,
  full_name text,
  role text,
  user_agent text,
  browser text,
  operating_system text,
  language text,
  timezone text,
  referrer text,
  page_url text,
  session_id text,
  ip_address text,
  accessed_at timestamptz not null default now(),
  status text not null default 'success',
  event_type text not null default 'admin_panel_access'
);

CREATE INDEX IF NOT EXISTS admin_access_logs_accessed_at_idx
  ON public.admin_access_logs (accessed_at DESC);

CREATE INDEX IF NOT EXISTS admin_access_logs_user_id_idx
  ON public.admin_access_logs (user_id);

ALTER TABLE public.admin_access_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admins y editores pueden ver accesos del panel" ON public.admin_access_logs;
CREATE POLICY "Admins y editores pueden ver accesos del panel"
ON public.admin_access_logs
FOR SELECT
USING (
  auth.uid() IS NOT NULL
  AND EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = auth.uid()
      AND p.role IN ('admin', 'editor')
      AND COALESCE(p.is_blocked, false) = false
  )
);

DROP POLICY IF EXISTS "Administradores pueden registrar accesos del panel" ON public.admin_access_logs;
CREATE POLICY "Administradores pueden registrar accesos del panel"
ON public.admin_access_logs
FOR INSERT
WITH CHECK (
  auth.uid() IS NOT NULL
  AND EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = auth.uid()
      AND p.role IN ('admin', 'editor')
      AND COALESCE(p.is_blocked, false) = false
  )
);

DROP POLICY IF EXISTS "Admins y editores pueden borrar accesos del panel" ON public.admin_access_logs;
CREATE POLICY "Admins y editores pueden borrar accesos del panel"
ON public.admin_access_logs
FOR DELETE
USING (
  auth.uid() IS NOT NULL
  AND EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = auth.uid()
      AND p.role IN ('admin', 'editor')
      AND COALESCE(p.is_blocked, false) = false
  )
);

SELECT
  u.id,
  u.email,
  p.full_name,
  p.role,
  p.is_blocked,
  p.blocked_reason,
  p.updated_at
FROM auth.users u
LEFT JOIN public.profiles p ON p.id = u.id
WHERE LOWER(u.email) = 'kentoterakawa@gmail.com';
