-- Ejecutar en Supabase SQL Editor
-- Registra cada acceso al panel administrativo con datos de sesión, navegador, host y contexto del usuario.
-- Script idempotente: se puede ejecutar varias veces sin romper la base.

create extension if not exists pgcrypto;

create table if not exists public.admin_access_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text,
  full_name text,
  role text,
  user_agent text,
  browser text,
  operating_system text,
  language text,
  timezone text,
  referrer text,
  page_url text,
  session_id text,
  ip_address text,
  accessed_at timestamptz not null default now(),
  status text not null default 'success',
  event_type text not null default 'admin_panel_access',
  created_at timestamptz not null default now()
);

create index if not exists admin_access_logs_accessed_at_idx
  on public.admin_access_logs (accessed_at desc);

create index if not exists admin_access_logs_user_id_idx
  on public.admin_access_logs (user_id, accessed_at desc);

create index if not exists admin_access_logs_role_idx
  on public.admin_access_logs (role, accessed_at desc);

create index if not exists admin_access_logs_status_idx
  on public.admin_access_logs (status, accessed_at desc);

create index if not exists admin_access_logs_event_type_idx
  on public.admin_access_logs (event_type, accessed_at desc);

alter table public.admin_access_logs enable row level security;

drop policy if exists "admins_and_editors_can_view_admin_access_logs" on public.admin_access_logs;
drop policy if exists "admins_and_editors_can_insert_admin_access_logs" on public.admin_access_logs;
drop policy if exists "admins_and_editors_can_delete_admin_access_logs" on public.admin_access_logs;
drop policy if exists "service_role_can_manage_admin_access_logs" on public.admin_access_logs;

create policy "admins_and_editors_can_view_admin_access_logs"
on public.admin_access_logs
for select
to authenticated
using (
  exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.role in ('admin', 'editor')
  )
);

create policy "admins_and_editors_can_insert_admin_access_logs"
on public.admin_access_logs
for insert
to authenticated
with check (
  auth.uid() is not null
  and exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.role in ('admin', 'editor')
  )
  and (
    user_id = auth.uid()
    or user_id is null
  )
);

create policy "admins_and_editors_can_delete_admin_access_logs"
on public.admin_access_logs
for delete
to authenticated
using (
  exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.role in ('admin', 'editor')
  )
);

create policy "service_role_can_manage_admin_access_logs"
on public.admin_access_logs
for all
to service_role
using (true)
with check (true);

create or replace function public.set_admin_access_log_defaults()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.user_id is null and auth.uid() is not null then
    new.user_id := auth.uid();
  end if;

  if new.email is null and auth.uid() is not null then
    new.email := coalesce(
      (select email from auth.users where id = auth.uid()),
      null
    );
  end if;

  if new.role is null and auth.uid() is not null then
    new.role := coalesce(
      (select role::text from public.profiles where id = auth.uid()),
      'reader'
    );
  end if;

  if new.full_name is null and auth.uid() is not null then
    new.full_name := coalesce(
      (select full_name from public.profiles where id = auth.uid()),
      null
    );
  end if;

  if new.accessed_at is null then
    new.accessed_at := now();
  end if;

  if new.status is null then
    new.status := 'success';
  end if;

  if new.event_type is null then
    new.event_type := 'admin_panel_access';
  end if;

  return new;
end;
$$;

drop trigger if exists admin_access_log_defaults_trigger on public.admin_access_logs;
create trigger admin_access_log_defaults_trigger
before insert on public.admin_access_logs
for each row
execute function public.set_admin_access_log_defaults();

